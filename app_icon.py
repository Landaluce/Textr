def app_icon_png_bytes():
    """Raw PNG bytes of the 256x256 logo."""
    raw = base64.b64decode(_APP_ICON_PNG_B64)
    assert len(raw) == _APP_ICON_PNG_LEN
    return raw


def get_app_icon():
    """QIcon for the Textr logo; a null icon if the data cannot load."""
    from PySide6.QtCore import QByteArray
    from PySide6.QtGui import QIcon, QImage, QPixmap

    image = QImage.fromData(QByteArray(app_icon_png_bytes()), "PNG")
    if image.isNull():
        return QIcon()
    pixmap = QPixmap.fromImage(image)
    if pixmap.isNull():
        return QIcon()
    return QIcon(pixmap)


def apply_app_icon(app):
    """Set the application (and desktop-file) identity on a QApplication.

    Never raises: a missing/broken icon must never stop startup.
    Returns the icon that was applied (possibly null).
    """
    try:
        icon = get_app_icon()
        if not icon.isNull():
            app.setWindowIcon(icon)
    except Exception:
        print("Could not set Textr window icon")
        icon = None
    try:
        app.setDesktopFileName("textr")
    except Exception:
        pass
    return icon
